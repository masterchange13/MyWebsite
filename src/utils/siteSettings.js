export const normalizeOrder = (order, availableIds) => {
  const input = Array.isArray(order) ? order : []
  const clean = []
  for (const id of input) {
    if (availableIds.includes(id) && !clean.includes(id)) clean.push(id)
  }
  for (const id of availableIds) {
    if (!clean.includes(id)) clean.push(id)
  }
  return clean
}

export const getOrderedSubmenuItems = (groupId, order) => {
  const defs = submenuDefinitions[groupId] || {}
  return normalizeOrder(order, Object.keys(defs)).map((id) => defs[id])
}

export const getOrderedTopLevelMenu = (topLevelOrder, submenuOrders) => {
  return normalizeOrder(topLevelOrder, Object.keys(topLevelMenuDefinitions)).map((id) => {
    const item = topLevelMenuDefinitions[id]
    if (item.type !== 'submenu') return item
    return {
      ...item,
      items: getOrderedSubmenuItems(id, submenuOrders?.[id])
    }
  })
}
